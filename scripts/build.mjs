#!/usr/bin/env node
// Builds tool-specific packages from the single source in skills/design-nexus.
//   dist/claude/design-nexus/                     Claude Code skill (~/.claude/skills or .claude/skills)
//   dist/codex/.agents/skills/design-nexus/       Codex skill
//   dist/codex/AGENTS.md                          block to merge into a project's AGENTS.md
//   dist/cursor/.cursor/rules/design-nexus.mdc    Cursor rule
//   dist/cursor/.cursor/design-nexus/             references, scripts, templates the rule points to
//   <skill>/design-trends/                        copy of docs/design-trends, for on-demand reads after install
//                                                 (not inlined into the Codex AGENTS.md block)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'skills/design-nexus');
const DIST = path.join(ROOT, 'dist');
const VERSION = fs.readFileSync(path.join(ROOT, 'VERSION'), 'utf8').trim();

const skill = fs.readFileSync(path.join(SRC, 'SKILL.md'), 'utf8');
const fm = skill.match(/^---\n([\s\S]*?)\n---\n/);
const meta = Object.fromEntries(fm[1].split('\n').map((l) => [l.slice(0, l.indexOf(':')).trim(), l.slice(l.indexOf(':') + 1).trim()]));
const body = skill.slice(fm[0].length);

// Point bare `references/…`, `scripts/…`, `templates/…` paths at an installed base folder.
const rebase = (text, base) => text.replace(/(^|[\s`(])((?:references|scripts|templates|design-trends)\/)/g, `$1${base}/$2`);
const banner = `<!-- design-nexus v${VERSION} · generated by scripts/build.mjs from skills/design-nexus/SKILL.md; edit the source, not this file -->\n`;

fs.rmSync(DIST, { recursive: true, force: true });
const copyDir = (to) => fs.cpSync(SRC, to, { recursive: true });
// On-demand trend database. Copied beside the skill so install.sh can read it.
// Do not inline it into the Codex AGENTS.md block; that file is always loaded.
const TRENDS = path.join(ROOT, 'docs/design-trends');
const copyTrends = (to) => {
  if (!fs.existsSync(path.join(TRENDS, 'latest.md'))) {
    throw new Error('docs/design-trends/latest.md is missing; the skill copy needs the trend database');
  }
  fs.cpSync(TRENDS, to, { recursive: true });
};

// Claude Code: the skill as is.
copyDir(path.join(DIST, 'claude/design-nexus'));
copyTrends(path.join(DIST, 'claude/design-nexus/design-trends'));

// Codex: native skill folder plus a short AGENTS.md block that is always loaded.
copyDir(path.join(DIST, 'codex/.agents/skills/design-nexus'));
copyTrends(path.join(DIST, 'codex/.agents/skills/design-nexus/design-trends'));
const floor = body.match(/## Non-negotiables \(Floor\)\n([\s\S]*?)\n## /)[1].trim();
fs.writeFileSync(path.join(DIST, 'codex/AGENTS.md'), [
  '<!-- design-nexus:start -->',
  banner.trim(),
  '## UI design work (design-nexus)',
  '',
  'For any task that builds, restyles, or reviews a user interface, read and follow `.agents/skills/design-nexus/SKILL.md` before writing UI code. Paths in that file are relative to `.agents/skills/design-nexus/`.',
  'If the project has a `DESIGN.md`, it is the source of truth for tokens and patterns; update it after UI work.',
  'Before reporting UI work as done, run `node .agents/skills/design-nexus/scripts/lint.mjs <changed files>` and fix every Floor (F) finding.',
  '',
  'Always, even for small UI changes:',
  '',
  floor.replace(/Full list with IDs in `references\/checks.md`\./, 'Full list in `.agents/skills/design-nexus/references/checks.md`.'),
  '<!-- design-nexus:end -->',
  '',
].join('\n'));

// Cursor: one rule auto-attached to UI files, resources beside it.
const cursorBase = '.cursor/design-nexus';
copyDir(path.join(DIST, 'cursor', cursorBase));
copyTrends(path.join(DIST, 'cursor', cursorBase, 'design-trends'));
fs.rmSync(path.join(DIST, 'cursor', cursorBase, 'SKILL.md'));
for (const dir of ['references', 'templates']) {
  for (const f of fs.readdirSync(path.join(DIST, 'cursor', cursorBase, dir))) {
    const p = path.join(DIST, 'cursor', cursorBase, dir, f);
    fs.writeFileSync(p, rebase(fs.readFileSync(p, 'utf8'), cursorBase));
  }
}
fs.mkdirSync(path.join(DIST, 'cursor/.cursor/rules'), { recursive: true });
const cursorBody = rebase(body, cursorBase)
  .replace('Scripts live in this skill\'s `scripts/` folder.', `Scripts live in \`${cursorBase}/scripts/\`.`)
  .replace('Paths below are relative to the skill folder; resolve them from wherever the skill is installed.', 'Run them from the project root.');
fs.writeFileSync(path.join(DIST, 'cursor/.cursor/rules/design-nexus.mdc'), [
  '---',
  `description: ${meta.description}`,
  'globs: **/*.{html,htm,css,scss,jsx,tsx,vue,svelte,astro}',
  'alwaysApply: false',
  '---',
  banner + cursorBody,
].join('\n'));

console.log(`built dist/ for design-nexus v${VERSION}: claude, codex, cursor`);
